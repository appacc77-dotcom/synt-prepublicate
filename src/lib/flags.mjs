/**
 * Флаги сборки.
 *
 * `figmaOnly` — сборка «только из макета»: блоки, которых нет в Figma
 * (изобретённые), не попадают в `dist`. Нужно, чтобы показать дизайнеру,
 * что на сайте строго из макета, и чтобы отличить «так нарисовано» от
 * «так придумано нами».
 *
 * Включается переменной окружения: `FIGMA_ONLY=1 npm run build`.
 */
export const figmaOnly = process.env.FIGMA_ONLY === '1';

/**
 * Слой дополнений студии: движение, поведение, подсказки.
 *
 * В режиме `base` (FIGMA_ONLY=1) дополнения выключены целиком: не только
 * элементы, но и обработчики, и стили движения. Иначе «сборка из макета» —
 * это косметика: разметка без блоков, но с чужим поведением.
 *
 * Компоненты проверяют не эту константу, а атрибут на `<html>`: скрипты
 * исполняются в браузере, где сборки уже нет. Константа нужна разметке.
 */
export const enhancementsOn = !figmaOnly;
